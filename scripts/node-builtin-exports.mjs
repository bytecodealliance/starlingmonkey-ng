// Prints `crates/builtins/node/src/exports_table.rs`: the export names of every Node.js builtin
// module, read from the running Node. Run it with the Node version the table should describe, and
// with the flags that make the flag-gated modules below loadable:
//
//     node --expose-internals --experimental-stream-iter scripts/node-builtin-exports.mjs \
//       > crates/builtins/node/src/exports_table.rs && cargo fmt
//
// Each export is classified as a class (a function whose name starts with an uppercase letter and
// whose prototype has own methods), a function, or another value. Primitive values are recorded
// verbatim, so a stub module can export the real constant.

import { builtinModules, createRequire } from "node:module";

const require = createRequire(import.meta.url);
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

// The modules that only exist with a runtime flag: the internal modules Node.js's tests load with
// `--expose-internals`, and the modules of `--experimental-stream-iter`.
const FLAGGED_MODULES = [
  "internal/assert/myers_diff",
  "internal/async_context_frame",
  "internal/async_hooks",
  "internal/blocklist",
  "internal/buffer",
  "internal/errors",
  "internal/event_target",
  "internal/fs/glob",
  "internal/fs/promises",
  "internal/fs/recursive_watch",
  "internal/fs/utils",
  "internal/fs/watchers",
  "internal/http",
  "internal/js_stream_socket",
  "internal/linkedlist",
  "internal/net",
  "internal/options",
  "internal/readline/utils",
  "internal/socketaddress",
  "internal/streams/add-abort-signal",
  "internal/streams/end-of-stream",
  "internal/streams/state",
  "internal/test/binding",
  "internal/timers",
  "internal/url",
  "internal/util",
  "internal/util/inspect",
  "stream/iter",
  "zlib/iter",
];

// A symbol is classified as such with `symbols`, and as another value otherwise.
function classify(value, symbols = false) {
  if (typeof value === "function") {
    const isClass =
      /^[A-Z]/.test(value.name) &&
      value.prototype &&
      Object.getOwnPropertyNames(value.prototype).length > 1;
    return isClass ? "Class" : "Function";
  }
  switch (typeof value) {
    case "string":
      return `Str(${JSON.stringify(value)})`;
    case "number":
      return Number.isFinite(value) ? `Num(${value}_f64)` : "Object";
    case "boolean":
      return `Bool(${value})`;
    case "undefined":
      return "Undefined";
    case "symbol":
      return symbols ? `Symbol(${JSON.stringify(value.description ?? "")})` : "Object";
    default:
      return value === null ? "Null" : "Object";
  }
}

// Modules listed with the `node:` prefix exist only under it. The others can also be imported
// without it.
function entries(names) {
  return names
    .map((name) =>
      name.startsWith("node:") ? { name, aliases: [] } : { name: `node:${name}`, aliases: [name] },
    )
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/**
 * The lines of the table entry of `module`, the value of builtin module `name`, with `kind`, the
 * kind of the value, for a module that only exists with a runtime flag.
 */
function exportLines(name, aliases, module, kind) {
  const lines = [
    `    (${JSON.stringify(name)}, &[${aliases.map((a) => JSON.stringify(a)).join(", ")}], ${kind ? `${kind}, ` : ""}&[`,
  ];
  for (const key of Object.keys(module).sort()) {
    if (!IDENTIFIER.test(key) || key === "default") continue;
    lines.push(`        (${JSON.stringify(key)}, ${classify(module[key], kind !== undefined)}),`);
  }
  lines.push("    ]),");
  return lines;
}

const lines = [
  "// SPDX-License-Identifier: Apache-2.0-WITH-LLVM-exception",
  "",
  `//! The exports of every Node.js builtin module, as Node.js ${process.version} defines them.`,
  "//!",
  "//! Generated by `scripts/node-builtin-exports.mjs`. Do not edit.",
  "",
  "use crate::stub::ExportKind::*;",
  "use crate::stub::{BuiltinEntry, FlaggedEntry};",
  "",
  "/// Each builtin module's name, the other specifiers that import it, and its exports, sorted by",
  "/// name.",
  "pub(crate) const BUILTIN_EXPORTS: &[BuiltinEntry] = &[",
];
const unflagged = builtinModules.filter(
  (name) => !name.startsWith("internal/") && !FLAGGED_MODULES.includes(name),
);
for (const { name, aliases } of entries(unflagged)) {
  let module;
  try {
    module = require(name);
  } catch {
    continue;
  }
  lines.push(...exportLines(name, aliases, module));
}
lines.push(
  "];",
  "",
  "/// The builtin modules that only exist with a runtime flag: each one's name, the other",
  "/// specifiers that import it, the kind of its value, and its exports, sorted by name.",
  "pub(crate) const FLAGGED_EXPORTS: &[FlaggedEntry] = &[",
);
for (const { name, aliases } of entries(FLAGGED_MODULES)) {
  const module = require(name);
  lines.push(...exportLines(name, aliases, module, classify(module)));
}
lines.push("];");
console.log(lines.join("\n"));
