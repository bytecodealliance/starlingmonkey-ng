//! The `starling-componentize` command line, run as a process in `tests/fixtures`.

mod shared;

use std::path::{Path, PathBuf};

use sha2::Digest as _;

static ENGINE: std::sync::LazyLock<wasmtime::Engine> = std::sync::LazyLock::new(shared::engine);

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

/// A fresh output directory for the test `name` under `CARGO_TARGET_TMPDIR`.
fn out_dir(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("cli-{name}"));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("creating the output directory");
    dir
}

/// Run the command line `args` in `tests/fixtures`, returning its stdout and
/// panicking with its stderr if it fails.
fn succeed(args: &[&str]) -> String {
    let output = shared::run_cli(args, Some(&fixtures()));
    assert!(
        output.status.success(),
        "`starling-componentize {}` failed:\n{}",
        args.join(" "),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).expect("UTF-8 output")
}

/// Run the command line `args` in `tests/fixtures`, returning its exit code and
/// stderr and panicking if it succeeds.
fn fail(args: &[&str]) -> (Option<i32>, String) {
    let output = shared::run_cli(args, Some(&fixtures()));
    assert!(
        !output.status.success(),
        "`starling-componentize {}` succeeded",
        args.join(" ")
    );
    (
        output.status.code(),
        String::from_utf8_lossy(&output.stderr).into_owned(),
    )
}

/// Two `-w` packages and two `-n` worlds build one component exporting both
/// worlds' functions. An explicit `--base-directory` resolves the input's
/// imports, `--init-location` sets `location` at init, and `--no-cache` builds
/// as well. Without `-q`, stdout holds what the application printed and the
/// success line.
#[tokio::test]
async fn merged_packages_and_worlds_build_and_run() -> anyhow::Result<()> {
    let output = out_dir("merged").join("merged.wasm");
    let output = output.to_str().expect("a UTF-8 path");
    let stdout = succeed(&[
        "-w",
        "cli/a.wit",
        "-w",
        "cli/b.wit",
        "-n",
        "test:cli-a/one",
        "-n",
        "two",
        "componentize",
        "cli/app/src/main.js",
        "--base-directory",
        "cli/app",
        "--init-location",
        "http://example.localhost/app/",
        "--no-cache",
        "-o",
        output,
    ]);
    assert_eq!(
        stdout,
        "initializing at http://example.localhost/app/\nComponent built successfully\n"
    );

    let component = wasmtime::component::Component::new(&ENGINE, std::fs::read(output)?)?;
    let linker = shared::linker(&ENGINE, &component, &[], |_| Ok(()));
    let mut store = shared::store(&ENGINE);
    let instance = linker.instantiate_async(&mut store, &component).await?;
    for (name, expected) in [("one", 41), ("two", 42)] {
        let func = instance.get_typed_func::<(), (u32,)>(&mut store, name)?;
        assert_eq!(
            func.call_async(&mut store, ()).await?,
            (expected,),
            "{name}"
        );
    }
    Ok(())
}

/// `types -o` writes the declarations to the file and names it on stdout,
/// which `-q` leaves empty.
#[test]
fn types_writes_its_output_file() {
    let dir = out_dir("types");
    let file = dir.join("a.d.ts");
    let file = file.to_str().expect("a UTF-8 path");
    assert_eq!(
        succeed(&["-w", "cli/a.wit", "types", "-o", file]),
        format!("Wrote TypeScript declarations to `{file}`\n")
    );
    let dts = std::fs::read_to_string(file).expect("reading the declarations");
    assert!(dts.starts_with("// Generated by"), "{dts}");
    assert!(dts.contains("one"), "{dts}");

    std::fs::remove_file(file).unwrap();
    assert_eq!(succeed(&["-q", "-w", "cli/a.wit", "types", "-o", file]), "");
    assert!(Path::new(file).exists());
}

/// `imports` lists `external` for a world that imports a function at world
/// level.
#[test]
fn imports_lists_external_for_world_level_imports() {
    let modules = succeed(&["-w", "surface.wit", "imports"]);
    assert!(modules.lines().any(|line| line == "external"), "{modules}");
}

/// `--version` names the runtime's digest and the version of the `init`
/// interface it implements.
#[test]
fn version_names_the_runtime() {
    let runtime = shared::runtime().expect("reading the runtime build");
    let stdout = succeed(&["--version"]);
    let lines: Vec<&str> = stdout.lines().collect();
    assert_eq!(
        lines[0],
        format!("starling-componentize {}", env!("CARGO_PKG_VERSION"))
    );
    assert_eq!(
        lines[1],
        format!("calls {}", componentize::init_interface_name())
    );
    assert_eq!(
        lines[2],
        format!(
            "runtime sha256:{}",
            hex::encode(sha2::Sha256::digest(runtime.module()))
        )
    );
    let implemented = componentize::runtime_init_interface(&runtime)
        .unwrap()
        .expect("the runtime implements the `init` interface");
    assert_eq!(lines[3], format!("runtime implements {implemented}"));
}

/// An input file that cannot be read fails, naming it.
#[test]
fn unreadable_input_fails() {
    let (_, stderr) = fail(&["--export-cli", "componentize", "missing.js"]);
    assert!(stderr.contains("unable to read `missing.js`"), "{stderr}");
}

/// A command line with neither a subcommand nor `--version` fails with a usage error.
#[test]
fn a_missing_subcommand_fails_with_a_usage_error() {
    let (code, stderr) = fail(&["--export-cli"]);
    assert_eq!(code, Some(2));
    assert!(
        stderr.contains("a subcommand or `--version` is required"),
        "{stderr}"
    );
}
